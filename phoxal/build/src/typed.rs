//! Typed client type generation from prepared descriptors.
//!
//! Prepared products generate their payload types through the same
//! [`phoxal::schema::PhoxalWire`] codec path as authored messages: scalar,
//! string, bytes, message, and enumeration fields all carry their Rust
//! types directly — no `i32` enum fields — and enumeration decoding
//! rejects unknown wire numbers instead of storing them. Prost remains the
//! wire implementation; the emitted `Message` implementations delegate to
//! the shared field codec, so authored and generated definitions of one
//! wire contract produce identical bytes.

use std::collections::{BTreeMap, BTreeSet};

use heck::{ToShoutySnakeCase, ToSnakeCase, ToUpperCamelCase};
use prost_reflect::{Cardinality, DescriptorPool, Kind, MessageDescriptor};

/// Mirrors `phoxal::schema::PAYLOAD_ENUM_ENVELOPE`: the internal oneof
/// name marking a message as a payload enum whose public Rust shape is an
/// ordinary enum, not a struct.
pub const PAYLOAD_ENUM_ENVELOPE: &str = "phoxal_envelope";

/// The envelope carrier oneof of a payload-enum message: its only
/// non-synthetic oneof, carrying the reserved name, with no ordinary
/// fields beside it.
fn envelope_of(message: &MessageDescriptor) -> Option<prost_reflect::OneofDescriptor> {
    let carriers: Vec<_> = message
        .oneofs()
        .filter(|oneof| !oneof.is_synthetic())
        .collect();
    if carriers.len() != 1 || carriers[0].name() != PAYLOAD_ENUM_ENVELOPE {
        return None;
    }
    let ordinary = message
        .fields()
        .filter(|field| {
            field
                .containing_oneof()
                .is_none_or(|oneof| oneof.is_synthetic())
        })
        .count();
    (ordinary == 0).then(|| carriers[0].clone())
}

/// Whether one envelope variant references an empty payload message: the
/// generated unit-variant form. Authored unit variants are the only empty
/// payloads an envelope carries (`google.protobuf.Empty` payloads are
/// rejected at authoring in favor of a unit variant).
fn is_unit_variant(field: &prost_reflect::FieldDescriptor) -> bool {
    match field.kind() {
        Kind::Message(message) => message.fields().count() == 0 && message.oneofs().count() == 0,
        _ => false,
    }
}

/// Emits every non-empty package's typed definitions, keyed by package
/// name for the generated include tree.
pub fn emit_typed_packages(pool: &DescriptorPool) -> BTreeMap<String, String> {
    emit_typed_packages_with_skips(pool, &BTreeSet::new())
}

/// Emits the typed definitions no other unit provides, keyed by package
/// name. A skipped definition's nested definitions skip with it; other
/// types sharing its package still emit.
pub fn emit_typed_packages_with_skips(
    pool: &DescriptorPool,
    skips: &BTreeSet<String>,
) -> BTreeMap<String, String> {
    let mut by_package: BTreeMap<String, String> = BTreeMap::new();
    for message in pool.all_messages() {
        let package = message.package_name().to_owned();
        // The SDK owns the standard vocabulary and the well-known types:
        // fields reference them there, and emitting copies here would
        // shadow the SDK definitions.
        if package.is_empty()
            || package.starts_with("google.protobuf")
            || crate::sdk_type_path(message.full_name()).is_some()
            || provided_elsewhere(message.full_name(), skips)
        {
            continue;
        }
        let output = by_package.entry(package.clone()).or_default();
        if let Some(carrier) = envelope_of(&message) {
            emit_payload_enum(output, &message, &carrier, &package);
        } else {
            emit_message(output, &message, &package);
        }
    }
    for enumeration in pool.all_enums() {
        let package = enumeration.package_name().to_owned();
        if package.is_empty()
            || package.starts_with("google.protobuf")
            || crate::sdk_type_path(enumeration.full_name()).is_some()
            || provided_elsewhere(enumeration.full_name(), skips)
        {
            continue;
        }
        let output = by_package.entry(package.clone()).or_default();
        emit_enum(output, &enumeration);
    }
    by_package
        .into_iter()
        .filter(|(_, output)| !output.is_empty())
        .map(|(package, output)| {
            (
                package,
                format!("// @generated by phoxal-build; do not edit.\n\n{output}"),
            )
        })
        .collect()
}

/// Whether a definition, or any definition nesting it, is provided by
/// another generated unit.
pub(crate) fn provided_elsewhere(full_name: &str, skips: &BTreeSet<String>) -> bool {
    if skips.contains(full_name) {
        return true;
    }
    let mut ancestor = full_name;
    while let Some(dot) = ancestor.rfind('.') {
        ancestor = &ancestor[..dot];
        if skips.contains(ancestor) {
            return true;
        }
    }
    false
}

/// The Rust path of one definition used as a field type: the SDK
/// vocabulary stays in the SDK, same-package references stay relative,
/// and everything else routes through the generated types root.
fn rust_type(full_name: &str, package: &str, home_package: &str) -> String {
    if let Some(path) = crate::sdk_type_path(full_name) {
        return path;
    }
    let Some(rest) = full_name.strip_prefix(&format!("{package}.")) else {
        return format!("crate::api::types::{}", full_name.replace('.', "::"));
    };
    if package == home_package {
        return rest.replace('.', "::");
    }
    format!(
        "crate::api::types::{}::{}",
        package.replace('.', "::"),
        rest.replace('.', "::")
    )
}

/// One analyzed message field.
struct Field {
    number: u32,
    name: String,
    ty: String,
    repeated: bool,
}

impl Field {
    fn parse(field: &prost_reflect::FieldDescriptor, package: &str) -> Option<Field> {
        let inner = match field.kind() {
            Kind::Double => "f64".to_owned(),
            Kind::Float => "f32".to_owned(),
            Kind::Int32 => "i32".to_owned(),
            Kind::Int64 => "i64".to_owned(),
            Kind::Uint32 => "u32".to_owned(),
            Kind::Uint64 => "u64".to_owned(),
            Kind::Bool => "bool".to_owned(),
            Kind::String => "String".to_owned(),
            Kind::Bytes => "::std::vec::Vec<u8>".to_owned(),
            Kind::Message(message) => {
                rust_type(message.full_name(), message.package_name(), package)
            }
            Kind::Enum(enumeration) => {
                rust_type(enumeration.full_name(), enumeration.package_name(), package)
            }
            other => {
                let _ = other;
                return None;
            }
        };
        let repeated = field.cardinality() == Cardinality::Repeated;
        Some(Field {
            number: field.number(),
            name: field.name().to_owned(),
            ty: if repeated {
                format!("::std::vec::Vec<{inner}>")
            } else if !repeated
                && (field.supports_presence() || matches!(field.kind(), Kind::Message(_)))
            {
                format!("::std::option::Option<{inner}>")
            } else {
                inner
            },
            repeated,
        })
    }
}

fn emit_message(output: &mut String, message: &MessageDescriptor, package: &str) {
    let name = message.name();
    let mut fields = Vec::<Field>::new();
    let mut oneofs = Vec::<(String, String, Vec<Field>)>::new();
    for field in message.fields() {
        if field
            .containing_oneof()
            .is_some_and(|oneof| !oneof.is_synthetic())
        {
            continue;
        }
        let Some(parsed) = Field::parse(&field, package) else {
            continue;
        };
        fields.push(parsed);
    }
    for oneof in message.oneofs().filter(|oneof| !oneof.is_synthetic()) {
        let mut variants = Vec::new();
        for field in oneof.fields() {
            let Some(mut parsed) = Field::parse(&field, package) else {
                continue;
            };
            parsed.ty = parsed
                .ty
                .trim_start_matches("::std::option::Option<")
                .trim_end_matches('>')
                .to_owned();
            variants.push(parsed);
        }
        if variants.is_empty() {
            continue;
        }
        oneofs.push((
            oneof.name().to_snake_case(),
            oneof.name().to_upper_camel_case(),
            variants,
        ));
    }

    let mut struct_fields = String::new();
    for field in &fields {
        struct_fields.push_str(&format!("    pub {}: {},\n", field.name, field.ty));
    }
    let message_module = name.to_snake_case();
    for (field_name, enum_name, _) in &oneofs {
        struct_fields.push_str(&format!(
            "    pub {field_name}: ::std::option::Option<{message_module}::{enum_name}>,\n"
        ));
    }
    output.push_str(&format!(
        "/// Generated from `{full_name}`.\n#[derive(Clone, Debug, PartialEq, Default)]\npub struct {name} {{\n{struct_fields}}}\n\n",
        full_name = message.full_name(),
    ));

    // prost::Name: the wire identity the pool recorded.
    let full_name = message.full_name();
    output.push_str(&format!(
        "impl ::phoxal::generated::prost::Name for {name} {{\n    \
         const NAME: &'static str = {name:?};\n    \
         const PACKAGE: &'static str = {package:?};\n    \
         fn full_name() -> ::phoxal::generated::prost::alloc::string::String {{\n        \
         ::phoxal::generated::prost::alloc::string::String::from({full_name:?})\n    }}\n    \
         fn type_url() -> ::phoxal::generated::prost::alloc::string::String {{\n        \
         ::phoxal::generated::prost::alloc::string::String::from(\"/{full_name}\")\n    }}\n}}\n\n"
    ));

    let mut encode = String::new();
    let mut merge = String::new();
    let mut len_terms = Vec::new();
    for field in &fields {
        let tag = field.number;
        let ident = &field.name;
        if field.repeated {
            encode.push_str(&format!(
                "        ::phoxal::schema::encode_repeated(&self.{ident}, {tag}, buf);\n"
            ));
            merge.push_str(&format!(
                "            {tag} => ::phoxal::schema::merge_repeated(&mut self.{ident}, \
                 wire_type, buf, ctx),\n"
            ));
            len_terms.push(format!(
                "::phoxal::schema::repeated_len(&self.{ident}, {tag})"
            ));
        } else {
            // Implicit presence: default-valued scalar, string, bytes, and
            // enumeration occurrences are omitted; explicit presence and
            // message fields always encode.
            encode.push_str(&format!(
                "        ::phoxal::schema::singular_encode(&self.{ident}, {tag}, buf);\n"
            ));
            merge.push_str(&format!(
                "            {tag} => ::phoxal::schema::PhoxalWire::phoxal_merge(\n                \
                 &mut self.{ident},\n                {tag},\n                wire_type,\n                \
                 buf,\n                ctx,\n            ),\n"
            ));
            len_terms.push(format!(
                "::phoxal::schema::singular_len(&self.{ident}, {tag})"
            ));
        }
    }
    for (field_name, _, variants) in &oneofs {
        let ident = field_name;
        for variant in variants {
            let oneof_tag = variant.number;
            merge.push_str(&format!(
                "            {oneof_tag} => ::phoxal::schema::PhoxalWire::phoxal_merge(\n                \
                 &mut self.{ident},\n                {oneof_tag},\n                wire_type,\n                \
                 buf,\n                ctx,\n            ),\n"
            ));
        }
        encode.push_str(&format!(
            "        if let ::std::option::Option::Some(variant) = &self.{ident} {{\n            \
             ::phoxal::schema::PhoxalWire::phoxal_encode(variant, 0, buf);\n        }}\n"
        ));
        len_terms.push(format!(
            "self.{ident}.as_ref().map_or(0, |variant| \
             ::phoxal::schema::PhoxalWire::phoxal_encoded_len(variant, 0))"
        ));
    }
    let len = if len_terms.is_empty() {
        "0".to_owned()
    } else {
        len_terms.join("\n            + ")
    };
    let empty_encode = if encode.is_empty() {
        "        let _ = buf;\n"
    } else {
        ""
    };
    let merge_body = if merge.is_empty() {
        "::phoxal::generated::prost::encoding::skip_field(wire_type, tag, buf, ctx)".to_owned()
    } else {
        format!(
            "match tag {{\n{merge}            \
             _ => ::phoxal::generated::prost::encoding::skip_field(wire_type, tag, buf, ctx),\n        \
             }}"
        )
    };
    output.push_str(&format!(
        "impl ::phoxal::generated::prost::Message for {name} {{\n    \
         fn encode_raw(&self, buf: &mut impl ::phoxal::generated::prost::bytes::BufMut) {{\n\
         {empty_encode}{encode}    }}\n\n    \
         fn merge_field(&mut self, tag: u32, \
         wire_type: ::phoxal::generated::prost::encoding::WireType, \
         buf: &mut impl ::phoxal::generated::prost::bytes::Buf, \
         ctx: ::phoxal::generated::prost::encoding::DecodeContext) \
         -> ::std::result::Result<(), ::phoxal::generated::prost::DecodeError> {{\n        \
         {merge_body}\n    }}\n\n    \
         fn encoded_len(&self) -> usize {{\n        {len}\n    }}\n\n    \
         fn clear(&mut self) {{\n        *self = Self::default();\n    }}\n}}\n\n"
    ));

    // The shared field codec: containing messages elsewhere reference this
    // definition through it.
    output.push_str(&format!(
        "impl ::phoxal::schema::PhoxalWire for {name} {{\n    \
         const WIRE_TYPE: ::phoxal::generated::prost::encoding::WireType =\n        \
         ::phoxal::generated::prost::encoding::WireType::LengthDelimited;\n    \
         const IS_ENUM: bool = false;\n    \
         const SKIP_DEFAULT: bool = false;\n\n    \
         fn phoxal_write<B: ::phoxal::generated::prost::bytes::BufMut>(&self, buf: &mut B) {{\n        \
         let len = <Self as ::phoxal::generated::prost::Message>::encoded_len(self);\n        \
         ::phoxal::generated::prost::encoding::encode_varint(len as u64, buf);\n        \
         <Self as ::phoxal::generated::prost::Message>::encode_raw(self, buf);\n    }}\n\n    \
         fn phoxal_value_len(&self) -> usize {{\n        \
         let len = <Self as ::phoxal::generated::prost::Message>::encoded_len(self);\n        \
         ::phoxal::generated::prost::encoding::encoded_len_varint(len as u64) + len\n    }}\n\n    \
         fn phoxal_merge<B: ::phoxal::generated::prost::bytes::Buf>(&mut self, \
         _tag: u32, wire_type: ::phoxal::generated::prost::encoding::WireType, buf: &mut B, \
         ctx: ::phoxal::generated::prost::encoding::DecodeContext) \
         -> ::std::result::Result<(), ::phoxal::generated::prost::DecodeError> {{\n        \
         ::phoxal::generated::prost::encoding::message::merge(wire_type, self, buf, ctx)\n    }}\n\n    \
         fn phoxal_merge_fresh<B: ::phoxal::generated::prost::bytes::Buf>(\
         tag: u32, wire_type: ::phoxal::generated::prost::encoding::WireType, buf: &mut B, \
         ctx: ::phoxal::generated::prost::encoding::DecodeContext) \
         -> ::std::result::Result<Self, ::phoxal::generated::prost::DecodeError> {{\n        \
         ::phoxal::schema::merge_fresh_default(tag, wire_type, buf, ctx)\n    }}\n}}\n\n\
         impl ::phoxal::contracts::ProstPayload for {name} {{\n    \
         type Wire = Self;\n\n    \
         fn to_wire(&self) -> Self {{\n        \
         <Self as ::std::clone::Clone>::clone(self)\n    }}\n\n    \
         fn try_from_wire(wire: Self) \
         -> ::std::result::Result<Self, ::phoxal::generated::prost::DecodeError> {{\n        \
         ::std::result::Result::Ok(wire)\n    }}\n}}\n\n"
    ));

    for (field_name, enum_name, variants) in &oneofs {
        emit_oneof(output, message, field_name, enum_name, variants);
    }
}

fn emit_oneof(
    output: &mut String,
    message: &MessageDescriptor,
    field_name: &str,
    enum_name: &str,
    variants: &[Field],
) {
    let mut variant_defs = String::new();
    let mut encode_arms = String::new();
    let mut write_arms = String::new();
    let mut value_len_arms = String::new();
    let mut merge_arms = String::new();
    let mut fresh_arms = String::new();
    let mut len_arms = String::new();
    // A single-variant oneof makes an `if let` binding irrefutable; emit
    // the exhaustive form so generated code stays warning-free under
    // `-D warnings` consumers.
    let single_variant = variants.len() == 1;
    for field in variants {
        let variant = field.name.to_upper_camel_case();
        let tag = field.number;
        // The oneof enum lives one nested module below the package, so
        // same-package payload definitions re-anchor through `super`.
        let ty = anchored(&field.ty);
        variant_defs.push_str(&format!("    {variant}({ty}),\n"));
        encode_arms.push_str(&format!(
            "            Self::{variant}(value) => \
             ::phoxal::schema::PhoxalWire::phoxal_encode(value, {tag}, buf),\n"
        ));
        write_arms.push_str(&format!(
            "            Self::{variant}(value) => \
             ::phoxal::schema::PhoxalWire::phoxal_write(value, buf),\n"
        ));
        value_len_arms.push_str(&format!(
            "            Self::{variant}(value) => \
             ::phoxal::schema::PhoxalWire::phoxal_value_len(value),\n"
        ));
        if single_variant {
            merge_arms.push_str(&format!(
                "            {tag} => {{\n                \
                 let Self::{variant}(value) = self;\n                \
                 ::phoxal::schema::PhoxalWire::phoxal_merge(value, {tag}, wire_type, buf, \
                 ctx)?;\n            }}\n"
            ));
        } else {
            merge_arms.push_str(&format!(
                "            {tag} => {{\n                \
                 // A repeated occurrence of the variant already selected merges\n                \
                 // into its payload, matching Prost's derived oneof decoders; a\n                \
                 // different variant starts a fresh payload.\n                \
                 if let Self::{variant}(value) = self {{\n                    \
                 ::phoxal::schema::PhoxalWire::phoxal_merge(value, {tag}, wire_type, buf, ctx)?;\n                \
                 }} else {{\n                    \
                 let mut value = <{ty} as ::std::default::Default>::default();\n                    \
                 ::phoxal::schema::PhoxalWire::phoxal_merge(&mut value, {tag}, wire_type, buf, \
                 ctx)?;\n                    \
                 *self = Self::{variant}(value);\n                \
                 }}\n            }}\n"
            ));
        }
        fresh_arms.push_str(&format!(
            "            {tag} => {{\n                \
             let mut value = <{ty} as ::std::default::Default>::default();\n                \
             ::phoxal::schema::PhoxalWire::phoxal_merge(&mut value, {tag}, wire_type, buf, \
             ctx)?;\n                \
             ::std::result::Result::Ok(Self::{variant}(value))\n            }}\n"
        ));
        len_arms.push_str(&format!(
            "            Self::{variant}(value) => \
             ::phoxal::schema::PhoxalWire::phoxal_encoded_len(value, {tag}),\n"
        ));
    }
    let first_variant = variants
        .first()
        .map(|field| field.name.to_upper_camel_case())
        .unwrap_or_default();
    let message_module = message.name().to_snake_case();
    output.push_str(&format!(
        "/// Generated from `{full_name}.{field_name}`.\npub mod {message_module} {{\n\
         #[derive(Clone, Debug, PartialEq)]\n    pub enum {enum_name} {{\n{variant_defs}    }}\n\n    \
         impl ::std::default::Default for {enum_name} {{\n        \
         fn default() -> Self {{\n            Self::{first_variant}(::std::default::Default::default())\n        }}\n    }}\n\n    \
         impl ::phoxal::schema::PhoxalWire for {enum_name} {{\n        \
         const WIRE_TYPE: ::phoxal::generated::prost::encoding::WireType =\n            \
         ::phoxal::generated::prost::encoding::WireType::LengthDelimited;\n        \
         const IS_ENUM: bool = false;\n        \
         const SKIP_DEFAULT: bool = false;\n\n        \
         fn phoxal_encode<B: ::phoxal::generated::prost::bytes::BufMut>(&self, \
         _outer_tag: u32, buf: &mut B) {{\n            match self {{\n{encode_arms}            }}\n        }}\n\n        \
         fn phoxal_write<B: ::phoxal::generated::prost::bytes::BufMut>(&self, buf: &mut B) {{\n            \
         match self {{\n{write_arms}            }}\n        }}\n\n        \
         fn phoxal_value_len(&self) -> usize {{\n            match self {{\n{value_len_arms}            }}\n        }}\n\n        \
         fn phoxal_merge<B: ::phoxal::generated::prost::bytes::Buf>(&mut self, tag: u32, \
         wire_type: ::phoxal::generated::prost::encoding::WireType, buf: &mut B, \
         ctx: ::phoxal::generated::prost::encoding::DecodeContext) \
         -> ::std::result::Result<(), ::phoxal::generated::prost::DecodeError> {{\n            \
         match tag {{\n{merge_arms}                \
         _ => return ::std::result::Result::Err(::phoxal::schema::unknown_oneof_tag(tag)),\n            \
         }}\n            ::std::result::Result::Ok(())\n        }}\n\n        \
         fn phoxal_merge_fresh<B: ::phoxal::generated::prost::bytes::Buf>(\
         tag: u32, wire_type: ::phoxal::generated::prost::encoding::WireType, buf: &mut B, \
         ctx: ::phoxal::generated::prost::encoding::DecodeContext) \
         -> ::std::result::Result<Self, ::phoxal::generated::prost::DecodeError> {{\n            \
         match tag {{\n{fresh_arms}                \
         _ => ::std::result::Result::Err(::phoxal::schema::unknown_oneof_tag(tag)),\n            \
         }}\n        }}\n\n        \
         fn phoxal_encoded_len(&self, _outer_tag: u32) -> usize {{\n            match self {{\n{len_arms}            }}\n        }}\n    }}\n}}\n\n",
        full_name = message.full_name(),
    ));
}

/// Re-anchors a same-package payload path for the oneof's nested module:
/// absolute, primitive, and prelude spellings resolve everywhere; bare
/// package-local names gain one `super` step.
fn anchored(ty: &str) -> String {
    const PRELUDE: [&str; 8] = ["f64", "f32", "i64", "i32", "u64", "u32", "bool", "String"];
    if ty.starts_with("::") || ty.starts_with("crate::") || PRELUDE.contains(&ty) {
        ty.to_owned()
    } else {
        format!("super::{ty}")
    }
}

fn emit_enum(output: &mut String, enumeration: &prost_reflect::EnumDescriptor) {
    let name = enumeration.name();
    // Authored value names carry the enumeration's own shouting prefix;
    // the variant ident is the remainder, matching Prost's convention.
    let value_prefix = format!("{}_", name.to_shouty_snake_case());
    let mut variants = String::new();
    for value in enumeration.values() {
        let variant = value
            .name()
            .strip_prefix(&value_prefix)
            .unwrap_or_else(|| value.name())
            .to_upper_camel_case();
        variants.push_str(&format!("    {variant} = {},\n", value.number()));
    }
    output.push_str(&format!(
        "/// Generated from `{full_name}`.\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, \
         PartialOrd, Ord, ::phoxal::generated::prost::Enumeration)]\n\
         #[prost(prost_path = \"::phoxal::generated::prost\")]\n#[repr(i32)]\npub enum {name} {{\n{variants}}}\n\n",
        full_name = enumeration.full_name(),
    ));
    output.push_str(&format!(
        "impl ::phoxal::schema::PhoxalWire for {name} {{\n    \
         const WIRE_TYPE: ::phoxal::generated::prost::encoding::WireType =\n        \
         ::phoxal::generated::prost::encoding::WireType::Varint;\n    \
         const IS_ENUM: bool = true;\n    \
         const SKIP_DEFAULT: bool = true;\n\n    \
         fn phoxal_write<B: ::phoxal::generated::prost::bytes::BufMut>(&self, buf: &mut B) {{\n        \
         let raw: i32 = ::std::convert::From::from(*self);\n        \
         ::phoxal::generated::prost::encoding::encode_varint(raw as i64 as u64, buf);\n    }}\n\n    \
         fn phoxal_value_len(&self) -> usize {{\n        \
         let raw: i32 = ::std::convert::From::from(*self);\n        \
         ::phoxal::generated::prost::encoding::encoded_len_varint(raw as i64 as u64)\n    }}\n\n    \
         fn phoxal_merge<B: ::phoxal::generated::prost::bytes::Buf>(&mut self, _tag: u32, \
         wire_type: ::phoxal::generated::prost::encoding::WireType, buf: &mut B, \
         ctx: ::phoxal::generated::prost::encoding::DecodeContext) \
         -> ::std::result::Result<(), ::phoxal::generated::prost::DecodeError> {{\n        \
         let mut raw: i32 = ::std::convert::From::from(*self);\n        \
         ::phoxal::generated::prost::encoding::int32::merge(wire_type, &mut raw, buf, ctx)?;\n        \
         *self = ::std::convert::TryFrom::try_from(raw)\n            \
         .map_err(::phoxal::schema::unknown_enum_value_error)?;\n        \
         ::std::result::Result::Ok(())\n    }}\n\n    \
         fn phoxal_merge_fresh<B: ::phoxal::generated::prost::bytes::Buf>(\
         tag: u32, wire_type: ::phoxal::generated::prost::encoding::WireType, buf: &mut B, \
         ctx: ::phoxal::generated::prost::encoding::DecodeContext) \
         -> ::std::result::Result<Self, ::phoxal::generated::prost::DecodeError> {{\n        \
         ::phoxal::schema::merge_fresh_default(tag, wire_type, buf, ctx)\n    }}\n}}\n\n",
    ));
}
/// Emits the public enum surface of one payload-enum envelope: the same
/// ordinary Rust enum shape authored services declare, with a private
/// wire mirror carrying the internal oneof and checked decoding that
/// rejects envelopes selecting no variant.
fn emit_payload_enum(
    output: &mut String,
    message: &MessageDescriptor,
    carrier: &prost_reflect::OneofDescriptor,
    package: &str,
) {
    let name = message.name();
    let module = format!("{}_wire", name.to_snake_case());
    let mut variant_defs = String::new();
    let mut to_wire_arms = String::new();
    let mut from_wire_arms = String::new();
    // A single-variant selection makes an `if let` binding irrefutable;
    // emit the exhaustive form so generated code stays warning-free.
    // Scalar variants stay inline on the wire mirror's enum but never
    // enter the selection oneof, so count only the selection-bearing
    // variants.
    let single_variant = carrier
        .fields()
        .filter(|field| matches!(field.kind(), Kind::Message(_)))
        .count()
        == 1;
    let mut selection_defs = String::new();
    let mut selection_encode_arms = String::new();
    let mut selection_write_arms = String::new();
    let mut selection_value_len_arms = String::new();
    let mut selection_merge_arms = String::new();
    let mut selection_fresh_arms = String::new();
    let mut selection_len_arms = String::new();
    let mut wire_merge_arms = String::new();
    for field in carrier.fields() {
        let variant = field.name().to_upper_camel_case();
        let tag = field.number();
        wire_merge_arms.push_str(&format!(
            "            {tag} => ::phoxal::schema::PhoxalWire::phoxal_merge(\
             &mut self.selection, {tag}, wire_type, buf, ctx),\n"
        ));
        if is_unit_variant(&field) {
            variant_defs.push_str(&format!("    {variant},\n"));
            to_wire_arms.push_str(&format!(
                "            Self::{variant} => Wire {{ selection: \
                 ::std::option::Option::Some(Selection::{variant}) }},\n"
            ));
            from_wire_arms.push_str(&format!(
                "            ::std::option::Option::Some(Selection::{variant}) => \
                 ::std::result::Result::Ok(Self::{variant}),\n"
            ));
            selection_defs.push_str(&format!("    {variant},\n"));
            // One unit-variant occurrence is a key plus a zero-length
            // length-delimited payload.
            selection_encode_arms.push_str(&format!(
                "            Selection::{variant} => {{\n                \
                 ::phoxal::generated::prost::encoding::encode_key(\
                 {tag}, ::phoxal::generated::prost::encoding::WireType::LengthDelimited, buf);\n \
                 ::phoxal::generated::prost::encoding::encode_varint(0_u64, buf);\n            }}\n"
            ));
            selection_write_arms.push_str(&format!(
                "            Selection::{variant} => \
                 ::phoxal::generated::prost::encoding::encode_varint(0_u64, buf),\n"
            ));
            selection_value_len_arms.push_str(&format!("            Selection::{variant} => 1,\n"));
            selection_len_arms.push_str(&format!(
                "            Selection::{variant} => \
                 ::phoxal::generated::prost::encoding::key_len({tag}) + 1,\n"
            ));
            if single_variant {
                selection_merge_arms.push_str(&format!(
                    "            {tag} => {{\n                \
                     let mut empty = ::phoxal::contracts::Empty::default();\n                \
                     ::phoxal::generated::prost::encoding::message::merge(\
                     wire_type, &mut empty, buf, ctx)?;\n            }}\n"
                ));
            } else {
                selection_merge_arms.push_str(&format!(
                    "            {tag} => {{\n                \
                     if let Selection::{variant} = self {{\n                    \
                     let mut empty = ::phoxal::contracts::Empty::default();\n                    \
                     ::phoxal::generated::prost::encoding::message::merge(\
                     wire_type, &mut empty, buf, ctx)?;\n                \
                     }} else {{\n                    \
                     let mut empty = ::phoxal::contracts::Empty::default();\n                    \
                     ::phoxal::generated::prost::encoding::message::merge(\
                     wire_type, &mut empty, buf, ctx)?;\n                    \
                     *self = Selection::{variant};\n                \
                     }}\n            }}\n"
                ));
            }
            selection_fresh_arms.push_str(&format!(
                "            {tag} => {{\n                \
                 let mut empty = ::phoxal::contracts::Empty::default();\n                \
                 ::phoxal::generated::prost::encoding::message::merge(\
                 wire_type, &mut empty, buf, ctx)?;\n                \
                 ::std::result::Result::Ok(Selection::{variant})\n            }}\n"
            ));
        } else {
            let Kind::Message(payload) = field.kind() else {
                continue;
            };
            let ty = rust_type(payload.full_name(), payload.package_name(), package);
            variant_defs.push_str(&format!("    {variant}({ty}),\n"));
            to_wire_arms.push_str(&format!(
                "            Self::{variant}(value) => Wire {{ selection: \
                 ::std::option::Option::Some(Selection::{variant}(\
                 ::std::clone::Clone::clone(value))) }},\n"
            ));
            from_wire_arms.push_str(&format!(
                "            ::std::option::Option::Some(Selection::{variant}(value)) => \
                 ::std::result::Result::Ok(Self::{variant}(value)),\n"
            ));
            selection_defs.push_str(&format!("    {variant}({ty}),\n"));
            selection_encode_arms.push_str(&format!(
                "            Selection::{variant}(value) => \
                 ::phoxal::schema::PhoxalWire::phoxal_encode(value, {tag}, buf),\n"
            ));
            selection_write_arms.push_str(&format!(
                "            Selection::{variant}(value) => \
                 ::phoxal::schema::PhoxalWire::phoxal_write(value, buf),\n"
            ));
            selection_value_len_arms.push_str(&format!(
                "            Selection::{variant}(value) => \
                 ::phoxal::schema::PhoxalWire::phoxal_value_len(value),\n"
            ));
            selection_len_arms.push_str(&format!(
                "            Selection::{variant}(value) => \
                 ::phoxal::schema::PhoxalWire::phoxal_encoded_len(value, {tag}),\n"
            ));
            if single_variant {
                selection_merge_arms.push_str(&format!(
                    "            {tag} => {{\n                \
                     let Selection::{variant}(value) = self;\n                \
                     ::phoxal::schema::PhoxalWire::phoxal_merge(\
                     value, {tag}, wire_type, buf, ctx)?;\n            }}\n"
                ));
            } else {
                selection_merge_arms.push_str(&format!(
                    "            {tag} => {{\n                \
                     if let Selection::{variant}(value) = self {{\n                    \
                     ::phoxal::schema::PhoxalWire::phoxal_merge(\
                     value, {tag}, wire_type, buf, ctx)?;\n                \
                     }} else {{\n                    \
                     let mut value = <{ty} as ::std::default::Default>::default();\n                    \
                     ::phoxal::schema::PhoxalWire::phoxal_merge(\
                     &mut value, {tag}, wire_type, buf, ctx)?;\n                    \
                     *self = Selection::{variant}(value);\n                \
                     }}\n            }}\n"
                ));
            }
            selection_fresh_arms.push_str(&format!(
                "            {tag} => {{\n                \
                 let mut value = <{ty} as ::std::default::Default>::default();\n                \
                 ::phoxal::schema::PhoxalWire::phoxal_merge(\
                 &mut value, {tag}, wire_type, buf, ctx)?;\n                \
                 ::std::result::Result::Ok(Selection::{variant}(value))\n            }}\n"
            ));
        }
    }
    output.push_str(&format!(
        "/// Generated from `{full_name}`: one payload enum owning its message \
         envelope.\n#[derive(Clone, Debug, PartialEq)]\npub enum {name} {{\n{variant_defs}}}\n\n",
        full_name = message.full_name(),
    ));
    output.push_str(&format!(
        "/// The private wire form of [`{name}`]: the internal oneof envelope.\nmod {module} {{\n    \
         use super::*;\n\n    \
         #[derive(Clone, Debug, PartialEq, Default)]\n    \
         pub struct Wire {{\n        \
         pub selection: ::std::option::Option<Selection>,\n    }}\n\n    \
         #[derive(Clone, Debug, PartialEq)]\n    \
         pub enum Selection {{\n{selection_defs}    }}\n\n    \
         impl ::phoxal::generated::prost::Message for Wire {{\n        \
         fn encode_raw(&self, buf: &mut impl ::phoxal::generated::prost::bytes::BufMut) {{\n            \
         if let ::std::option::Option::Some(selection) = &self.selection {{\n                \
         ::phoxal::schema::PhoxalWire::phoxal_encode(selection, 0, buf);\n            \
         }}\n        }}\n\n        \
         fn merge_field(&mut self, tag: u32, \
         wire_type: ::phoxal::generated::prost::encoding::WireType, \
         buf: &mut impl ::phoxal::generated::prost::bytes::Buf, \
         ctx: ::phoxal::generated::prost::encoding::DecodeContext) \
         -> ::std::result::Result<(), ::phoxal::generated::prost::DecodeError> {{\n            \
         match tag {{\n{wire_merge_arms}                \
         _ => ::phoxal::generated::prost::encoding::skip_field(\
         wire_type, tag, buf, ctx),\n            \
         }}\n        }}\n\n        \
         fn encoded_len(&self) -> usize {{\n            \
         self.selection.as_ref().map_or(0, |selection| \
         ::phoxal::schema::PhoxalWire::phoxal_encoded_len(selection, 0))\n        }}\n\n        \
         fn clear(&mut self) {{\n            *self = Self::default();\n        }}\n    }}\n\n    \
         impl ::phoxal::schema::PhoxalWire for Selection {{\n        \
         const WIRE_TYPE: ::phoxal::generated::prost::encoding::WireType =\n            \
         ::phoxal::generated::prost::encoding::WireType::LengthDelimited;\n        \
         const IS_ENUM: bool = false;\n        \
         const SKIP_DEFAULT: bool = false;\n\n        \
         fn phoxal_encode<B: ::phoxal::generated::prost::bytes::BufMut>(&self, \
         _outer_tag: u32, buf: &mut B) {{\n            match self {{\n{selection_encode_arms}            }}\n        }}\n\n        \
         fn phoxal_write<B: ::phoxal::generated::prost::bytes::BufMut>(&self, buf: &mut B) {{\n            \
         match self {{\n{selection_write_arms}            }}\n        }}\n\n        \
         fn phoxal_value_len(&self) -> usize {{\n            match self {{\n{selection_value_len_arms}            }}\n        }}\n\n        \
         fn phoxal_merge<B: ::phoxal::generated::prost::bytes::Buf>(&mut self, tag: u32, \
         wire_type: ::phoxal::generated::prost::encoding::WireType, buf: &mut B, \
         ctx: ::phoxal::generated::prost::encoding::DecodeContext) \
         -> ::std::result::Result<(), ::phoxal::generated::prost::DecodeError> {{\n            \
         match tag {{\n{selection_merge_arms}                \
         _ => return ::std::result::Result::Err(::phoxal::schema::unknown_oneof_tag(tag)),\n            \
         }}\n            ::std::result::Result::Ok(())\n        }}\n\n        \
         fn phoxal_merge_fresh<B: ::phoxal::generated::prost::bytes::Buf>(\
         tag: u32, wire_type: ::phoxal::generated::prost::encoding::WireType, buf: &mut B, \
         ctx: ::phoxal::generated::prost::encoding::DecodeContext) \
         -> ::std::result::Result<Self, ::phoxal::generated::prost::DecodeError> {{\n            \
         match tag {{\n{selection_fresh_arms}                \
         _ => ::std::result::Result::Err(::phoxal::schema::unknown_oneof_tag(tag)),\n            \
         }}\n        }}\n\n        \
         fn phoxal_encoded_len(&self, _outer_tag: u32) -> usize {{\n            match self {{\n{selection_len_arms}            }}\n        }}\n    }}\n\n    \
         impl ::phoxal::contracts::ProstPayload for {name} {{\n        \
         type Wire = Wire;\n\n        \
         fn to_wire(&self) -> Wire {{\n            match self {{\n{to_wire_arms}            }}\n        }}\n\n        \
         fn try_from_wire(wire: Wire) \
         -> ::std::result::Result<Self, ::phoxal::generated::prost::DecodeError> {{\n            \
         match wire.selection {{\n{from_wire_arms}                \
         ::std::option::Option::None => ::std::result::Result::Err(\n                    \
         ::phoxal::schema::missing_variant_error({wire_name:?}),\n                \
         ),\n            \
         }}\n        }}\n    }}\n\n    \
         impl ::phoxal::schema::PhoxalWire for {name} {{\n        \
         const WIRE_TYPE: ::phoxal::generated::prost::encoding::WireType =\n            \
         ::phoxal::generated::prost::encoding::WireType::LengthDelimited;\n        \
         const IS_ENUM: bool = false;\n        \
         const SKIP_DEFAULT: bool = false;\n\n        \
         fn phoxal_write<B: ::phoxal::generated::prost::bytes::BufMut>(&self, buf: &mut B) {{\n            \
         let wire = <Self as ::phoxal::contracts::ProstPayload>::to_wire(self);\n            \
         let len = <Wire as ::phoxal::generated::prost::Message>::encoded_len(&wire);\n            \
         ::phoxal::generated::prost::encoding::encode_varint(len as u64, buf);\n            \
         <Wire as ::phoxal::generated::prost::Message>::encode_raw(&wire, buf);\n        }}\n\n        \
         fn phoxal_value_len(&self) -> usize {{\n            \
         let wire = <Self as ::phoxal::contracts::ProstPayload>::to_wire(self);\n            \
         let len = <Wire as ::phoxal::generated::prost::Message>::encoded_len(&wire);\n            \
         ::phoxal::generated::prost::encoding::encoded_len_varint(len as u64) + len\n        }}\n\n        \
         fn phoxal_merge<B: ::phoxal::generated::prost::bytes::Buf>(&mut self, \
         _tag: u32, wire_type: ::phoxal::generated::prost::encoding::WireType, buf: &mut B, \
         ctx: ::phoxal::generated::prost::encoding::DecodeContext) \
         -> ::std::result::Result<(), ::phoxal::generated::prost::DecodeError> {{\n            \
         let mut wire = <Self as ::phoxal::contracts::ProstPayload>::to_wire(self);\n            \
         ::phoxal::generated::prost::encoding::message::merge(\
         wire_type, &mut wire, buf, ctx)?;\n            \
         *self = <Self as ::phoxal::contracts::ProstPayload>::try_from_wire(wire)?;\n            \
         ::std::result::Result::Ok(())\n        }}\n\n        \
         fn phoxal_merge_fresh<B: ::phoxal::generated::prost::bytes::Buf>(\
         _tag: u32, wire_type: ::phoxal::generated::prost::encoding::WireType, buf: &mut B, \
         ctx: ::phoxal::generated::prost::encoding::DecodeContext) \
         -> ::std::result::Result<Self, ::phoxal::generated::prost::DecodeError> {{\n            \
         let mut wire = <Wire as ::std::default::Default>::default();\n            \
         ::phoxal::generated::prost::encoding::message::merge(\
         wire_type, &mut wire, buf, ctx)?;\n            \
         <Self as ::phoxal::contracts::ProstPayload>::try_from_wire(wire)\n        }}\n    }}\n}}\n\n",
        wire_name = message.full_name(),
    ));
}
