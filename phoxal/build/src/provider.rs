//! Provider-glue generation for resolved service documents.
//!
//! The emitted module is attached by `#[phoxal::runtime]` and stays private
//! implementation glue; authored code uses `api::calls` for requirement
//! handles and `api::projections` for projection hooks.  The attributed
//! forms reuse the ordinary `runtime::inputs`/`runtime::outputs` expansions
//! so the manifest adds no second macro semantics.

use heck::ToShoutySnakeCase;

use crate::manifest::{Delivery, ResolvedService};

/// Emits the provider module for one resolved service document.
pub(crate) fn emit_provider(resolved: &ResolvedService) -> String {
    let mut output = String::from("// @generated by phoxal-build; do not edit.\n");
    output.push_str(
        "// Provider glue for this package's service declaration. Attached by\n\
         // `#[phoxal::runtime]`; authored code uses `api::calls` and\n\
         // `api::projections` instead of this module.\n\n",
    );

    emit_inputs(resolved, &mut output);
    emit_outputs(resolved, &mut output);
    emit_projections(resolved, &mut output);
    output
}

fn emit_inputs(resolved: &ResolvedService, output: &mut String) {
    output.push_str("#[::phoxal::runtime::inputs]\npub struct Inputs {\n");
    for input in &resolved.inputs {
        let message = &input.message.rust_path;
        match (input.delivery, input.lease_valid_for_ms) {
            (Delivery::Latest, None) => {
                let max_age = input
                    .max_age_ms
                    .map_or_else(String::new, |value| format!("max_age_ms = {value}, "));
                output.push_str(&format!(
                    "    #[::phoxal::runtime::input({max_age}max_bytes = {})]\n    pub {}: ::phoxal::runtime::input::Latest<{message}>,\n",
                    input.max_bytes, input.name
                ));
            }
            (Delivery::Latest, Some(_)) => {
                let max_age = input
                    .max_age_ms
                    .map_or_else(String::new, |value| format!("max_age_ms = {value}, "));
                let constant = input.name.to_shouty_snake_case();
                output.push_str(&format!(
                    "    #[::phoxal::runtime::input(port = crate::api::service_methods::u0::{constant}.setpoint_port(), {max_age}max_bytes = {})]\n    pub {}: ::phoxal::runtime::input::Setpoint<{message}>,\n",
                    input.max_bytes, input.name
                ));
            }
            (Delivery::Queue, _) => {
                let max_items = input.max_items.unwrap_or(1);
                output.push_str(&format!(
                    "    #[::phoxal::runtime::input(max_items = {max_items}, max_bytes = {})]\n    pub {}: ::phoxal::runtime::input::Samples<{message}>,\n",
                    input.max_bytes, input.name
                ));
            }
        }
    }
    for operation in &resolved.operations {
        let constant = operation.name.to_shouty_snake_case();
        output.push_str(&format!(
            "    #[::phoxal::runtime::input(port = crate::api::service_methods::u0::{constant}.commands_port(), max_items = {}, max_bytes = {})]\n    pub {}: ::phoxal::runtime::input::Commands<{}, {}>,\n",
            operation.max_items,
            operation.max_bytes,
            operation.name,
            operation.request.rust_path,
            operation.response.rust_path
        ));
    }
    for call in &resolved.calls {
        let constant = call.name.to_shouty_snake_case();
        output.push_str(&format!(
            "    #[::phoxal::runtime::input(port = crate::api::service_methods::u0::{constant}.commands_port(), max_items = {}, max_bytes = {})]\n    pub {}: ::phoxal::runtime::input::Completions,\n",
            call.max_items, call.max_bytes, call.name
        ));
    }
    output.push_str("}\n\n");

    // Apply each declared age bound without making the author repeat it in Rust.
    let freshness = resolved
        .inputs
        .iter()
        .filter(|input| input.delivery == Delivery::Latest && input.max_age_ms.is_some())
        .map(|input| {
            format!(
                "    /// Reports whether `{}` satisfies its declared {} ms age bound at `now`.\n    pub fn {}_fresh(&self, now: ::phoxal::runtime::ExecutionTime) -> bool {{\n        self.{}.is_fresh_at(now, ::std::option::Option::Some({}))\n    }}\n",
                input.name,
                input.max_age_ms.unwrap_or_default(),
                input.name,
                input.name,
                input.max_age_ms.unwrap_or_default()
            )
        })
        .collect::<Vec<_>>()
        .join("");
    if !freshness.is_empty() {
        output.push_str("impl Inputs {\n");
        output.push_str(&freshness);
        output.push_str("}\n\n");
    }
}

fn emit_outputs(resolved: &ResolvedService, output: &mut String) {
    output.push_str("#[derive(Default)]\n#[::phoxal::runtime::outputs]\npub struct Outputs {\n");
    for endpoint in &resolved.outputs {
        if endpoint.projection {
            continue;
        }
        match endpoint.delivery {
            Delivery::Latest => {
                let constant = endpoint.name.to_shouty_snake_case();
                output.push_str(&format!(
                    "    #[::phoxal::runtime::outputs::state(port = crate::api::service_methods::u0::{constant}.state_port(), max_bytes = {})]\n    pub {}: ::std::option::Option<{}>,\n",
                    endpoint.max_bytes,
                    endpoint.name,
                    endpoint.message.rust_path
                ));
            }
            Delivery::Queue => {
                let constant = endpoint.name.to_shouty_snake_case();
                let max_items = endpoint.max_items.unwrap_or(1);
                output.push_str(&format!(
                    "    #[::phoxal::runtime::outputs::event(port = crate::api::service_methods::u0::{constant}.event_port(), max_items = {max_items}, max_bytes = {})]\n    pub {}: ::std::vec::Vec<{}>,\n",
                    endpoint.max_bytes,
                    endpoint.name,
                    endpoint.message.rust_path
                ));
            }
        }
    }
    for operation in &resolved.operations {
        output.push_str(&format!(
            "    #[::phoxal::runtime::outputs::reply({}, max_items = {}, max_bytes = {})]\n    pub {}_replies: ::std::vec::Vec<::phoxal::runtime::Reply<{}>>,\n",
            operation.name,
            operation.max_items,
            operation.max_bytes,
            operation.name,
            operation.response.rust_path
        ));
    }
    output.push_str("    operations: ::phoxal::runtime::outputs::Outputs,\n");
    output.push_str("}\n\n");

    output.push_str("impl Outputs {\n");
    for endpoint in &resolved.outputs {
        if endpoint.projection {
            continue;
        }
        match endpoint.delivery {
            Delivery::Latest => output.push_str(&format!(
                "    /// Publishes the retained `{}` observation for this step.\n    pub fn {}(&mut self, value: {}) -> ::phoxal::Result<()> {{\n        self.{} = ::std::option::Option::Some(value);\n        ::std::result::Result::Ok(())\n    }}\n",
                endpoint.name, endpoint.name, endpoint.message.rust_path, endpoint.name
            )),
            Delivery::Queue => output.push_str(&format!(
                "    /// Publishes one `{}` batch for this step.\n    pub fn {}(&mut self, values: ::std::vec::Vec<{}>) -> ::phoxal::Result<()> {{\n        self.{} = values;\n        ::std::result::Result::Ok(())\n    }}\n",
                endpoint.name, endpoint.name, endpoint.message.rust_path, endpoint.name
            )),
        }
    }
    for operation in &resolved.operations {
        output.push_str(&format!(
            "    /// Replies to one accepted `{}` request.\n    pub fn {}_reply(&mut self, reply: ::phoxal::runtime::Reply<{}>) -> ::phoxal::Result<()> {{\n        self.{}_replies.push(reply);\n        ::std::result::Result::Ok(())\n    }}\n",
            operation.name, operation.name, operation.response.rust_path, operation.name
        ));
    }
    if resolved.calls.is_empty() {
        output.push_str(
            "    #[allow(dead_code, reason = \"kept symmetric with calling services\")]\n    pub(crate) fn operations(&mut self) -> &mut ::phoxal::runtime::outputs::Outputs {\n        &mut self.operations\n    }\n",
        );
    } else {
        output.push_str(
            "    /// Stages one generated call; its typed completion arrives in a later input cut.\n    pub fn send<O>(&mut self, context: &::phoxal::runtime::StepContext, operation: O) -> ::phoxal::Result<::phoxal::runtime::outputs::CallTicket<O::Response>>\n    where\n        O: ::phoxal::runtime::outputs::GeneratedSend,\n    {\n        self.operations.send(context, operation)\n    }\n",
        );
    }
    output.push_str("}\n\n");
}

fn emit_projections(resolved: &ResolvedService, output: &mut String) {
    let projections: Vec<_> = resolved
        .outputs
        .iter()
        .filter(|endpoint| endpoint.projection)
        .collect();

    output.push_str("macro_rules! attach_provider {\n    ($ty:ty, $state:ty) => {\n");
    if projections.is_empty() {
        output.push_str("        impl ::phoxal::runtime::outputs::OutputBindings for $ty {\n            const FIELDS: &'static [::phoxal::runtime::outputs::OutputField] = &[];\n        }\n");
    } else {
        output.push_str(
            "        #[::phoxal::runtime::outputs]\n        #[allow(dead_code, reason = \"the transport runner invokes output projections\")]\n        impl $ty {\n",
        );
        for endpoint in &projections {
            let constant = endpoint.name.to_shouty_snake_case();
            if let Some(valid_for_ms) = endpoint.lease_valid_for_ms {
                output.push_str(&format!(
                    "            #[::phoxal::runtime::outputs::setpoint(port = crate::api::service_methods::u0::{constant}.setpoint_port(), max_bytes = {}, valid_for_ms = {valid_for_ms})]\n            fn {name}(&self, state: &$state) -> ::std::option::Option<{message}> {{\n                <$ty as crate::api::projections::Projections>::{name}(self, state)\n            }}\n",
                    endpoint.max_bytes,
                    name = endpoint.name,
                    message = endpoint.message.rust_path,
                ));
            } else {
                let mut flags = String::new();
                if endpoint.bootstrap {
                    flags.push_str(", bootstrap");
                }
                if endpoint.on_change {
                    flags.push_str(", on_change");
                }
                output.push_str(&format!(
                    "            #[::phoxal::runtime::outputs::state(port = crate::api::service_methods::u0::{constant}.state_port(), max_bytes = {}{flags})]\n            fn {name}(&self, state: &$state) -> {message} {{\n                <$ty as crate::api::projections::Projections>::{name}(self, state)\n            }}\n",
                    endpoint.max_bytes,
                    name = endpoint.name,
                    message = endpoint.message.rust_path,
                ));
            }
        }
        output.push_str("        }\n");
    }
    output.push_str("    };\n}\npub(crate) use attach_provider;\n");
}
